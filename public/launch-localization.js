export function localizeName(value = '') {
  let result = String(value || '');
  for (const [original, zh] of Object.entries(REFERENCE_TITLES)) result=result.split(original).join(zh);
  for (const [pattern, replacement] of rules) result = result.replace(pattern, replacement);
  return result;
}
export function localizeLaunch(launch) {
  const agency = launch.agency || {};
  const translatedAgency = localizeAgency(agency.originalName || agency.name || '');
  return {...launch, name: localizeName(launch.name), rocket: localizeName(launch.rocket),
    agency: {...agency, name: translatedAgency !== (agency.originalName || agency.name) ? translatedAgency : agency.name},
    mission: launch.mission ? {...launch.mission, name: localizeName(launch.mission.name)} : launch.mission};
}
