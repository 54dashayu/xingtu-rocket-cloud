import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const fuels=new Set(['kerolox','methalox','hydrolox','hypergolic','hypergolic_mmh','liquid_unspecified','solid']);
export function compilePropulsionDatabase(db){
 if(db.schemaVersion!==1||!db.version||!Array.isArray(db.models)||!db.sources)throw Error('推进剂库格式不正确');
 const ids=new Set(),aliases=new Set();
 const source=id=>{const s=db.sources[id];if(!s||!/^https:\/\//.test(s.url))throw Error('缺少来源: '+id);return s;};
 return db.models.map(r=>{
  if(!r.id||ids.has(r.id)||!r.aliases?.length||!r.components?.length)throw Error('型号重复或缺失: '+r.id);ids.add(r.id);
  for(const a of r.aliases){const k=a.trim().toLowerCase();if(!k||aliases.has(k))throw Error('型号别名重复: '+a);aliases.add(k);}
  const components=structuredClone(r.components),componentsById=new Map();
  for(const c of components){
   if(componentsById.has(c.id)||!['stage','booster'].includes(c.kind)||!c.sourceRefs?.length)throw Error('组件/来源缺失: '+r.id);
   c.sourceRefs.forEach(source);componentsById.set(c.id,c);c.fieldSources={fuel:c.sourceRefs[0],engines:c.sourceRefs[0]};
  }
  // Exact configuration and exact field only. Official values always win over
  // reviewed supplementary values. Network review artifacts never enter here.
  for(const o of r.officialOverrides||[]){
   const c=componentsById.get(o.component),s=source(o.sourceRef);
   if(!c||s.kind!=='official')throw Error('官方覆盖必须有对应组件及官方来源');
   for(const [k,v]of Object.entries(o.values)){
    if(!['fuel','count','engines'].includes(k))throw Error('不允许覆盖字段 '+k);
    c[k]=structuredClone(v);c.fieldSources[k]=o.sourceRef;
   }
   c.sourceRefs=[o.sourceRef,...c.sourceRefs.filter(x=>x!==o.sourceRef)];
  }
  for(const c of components){
   if(!fuels.has(c.fuel)||!Array.isArray(c.engines))throw Error('未知推进剂或发动机字段: '+r.id);
   if(c.kind==='booster'&&(!Number.isInteger(c.count)||c.count<1))throw Error('助推器数量无效');
   for(const e of c.engines)if(!e.model||!Number.isInteger(e.count)||e.count<1||!['台','组','套'].includes(e.unit)||!e.scope)throw Error('发动机记录缺失: '+r.id);
  }
  if(r.referenceBasis==='flown_model_reference'&&(r.flightEvidence?.status!=='flown'||!r.flightEvidence.sourceRefs?.length))throw Error('缺少已飞证据: '+r.id);
  (r.flightEvidence?.sourceRefs||[]).forEach(source);
  const refs=[...new Set([...components.flatMap(c=>c.sourceRefs),...(r.flightEvidence?.sourceRefs||[])])];
  refs.sort((a,b)=>['official','reference','encyclopedia'].indexOf(source(a).kind)-['official','reference','encyclopedia'].indexOf(source(b).kind));
  const compact=c=>({...c});
  return {id:r.id,name:r.name,aliases:r.aliases,...(r.provider?{provider:r.provider}:{}),...(r.referenceBasis?{referenceBasis:r.referenceBasis}:{}),...(r.flightEvidence?{flightEvidence:r.flightEvidence}:{}),configurationScope:r.configurationScope,boostersKnown:r.boostersKnown!==false,
   stages:components.filter(c=>c.kind==='stage').map(compact),boosters:components.filter(c=>c.kind==='booster').map(compact),
   sources:refs.map(x=>({id:x,...source(x)})),checkedAt:db.checkedAt};
 });
}
export async function buildPropulsionDatabase(){
 const files=['long-march','commercial'];
 const databases=await Promise.all(files.map(name=>readFile(new URL('../data/propulsion/'+name+'.json',import.meta.url),'utf8').then(JSON.parse)));
 const merged={schemaVersion:1,version:databases.map(d=>d.version).join('+'),checkedAt:'2026-11-23',sources:Object.assign({},...databases.map(d=>d.sources)),models:databases.flatMap(d=>d.models)};
 const records=compilePropulsionDatabase(merged),longMarchRecords=compilePropulsionDatabase(databases[0]);
 const module=(comment,versionName,recordsName,version,rows)=>'// Generated by scripts/build-propulsion-db.mjs. '+comment+'\nexport const '+versionName+'='+JSON.stringify(version)+';\nexport const '+recordsName+'='+JSON.stringify(rows)+';\n';
 // Validate the entire merged catalog before writing either generated asset.
 await writeFile(new URL('../public/map/long-march-data.js',import.meta.url),module('Edit data/propulsion/long-march.json.','LONG_MARCH_VERSION','LONG_MARCH_RECORDS',databases[0].version,longMarchRecords));
 await writeFile(new URL('../public/map/propulsion-data.js',import.meta.url),module('Edit data/propulsion/*.json.','PROPULSION_DATABASE_VERSION','PROPULSION_RECORDS',merged.version,records));
 return records.length;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log('已生成本地型号库:',await buildPropulsionDatabase());
